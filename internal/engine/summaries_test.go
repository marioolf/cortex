// TestHelperSummariser is the fake summariser: the test binary running itself
// (see package summarize's test). Mode and files come from the environment.
func TestHelperSummariser(t *testing.T) {
	mode := os.Getenv("CORTEX_FAKE_MODE")
	if mode == "" {
		t.Skip("helper")
	}
	in, _ := io.ReadAll(os.Stdin)
	if f := os.Getenv("CORTEX_FAKE_COUNT"); f != "" {
		fh, _ := os.OpenFile(f, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o600)
		fh.WriteString("run\n")
		fh.Close()
	}
	if f := os.Getenv("CORTEX_FAKE_PROMPT"); f != "" {
		os.WriteFile(f, in, 0o600)
	}
	switch mode {
	case "ok":
		fmt.Print("Fake summary.")
	case "fail":
		fmt.Fprint(os.Stderr, "boom: not logged in")
		os.Exit(3)
	case "block":
		os.WriteFile(os.Getenv("CORTEX_FAKE_STARTED"), nil, 0o600)
		for i := 0; i < 1000; i++ {
			if _, err := os.Stat(os.Getenv("CORTEX_FAKE_RELEASE")); err == nil {
				break
			}
			time.Sleep(20 * time.Millisecond)
		}
		fmt.Print("Blocked summary.")
	}
	os.Exit(0)
}

type clock struct {
	mu sync.Mutex
	t  time.Time
}

func (c *clock) Now() time.Time  { c.mu.Lock(); defer c.mu.Unlock(); return c.t }
func (c *clock) Set(t time.Time) { c.mu.Lock(); c.t = t; c.mu.Unlock() }
func (c *clock) Add(d time.Duration) {
	c.mu.Lock()
	c.t = c.t.Add(d)
	c.mu.Unlock()
}

// sumEnv is an engine whose summaries run the fake through the custom command.
type sumEnv struct {
	e       *Engine
	f       *fake
	clk     *clock
	vault   string
	count   string // file the fake appends a line to on every run
	prompt  string
	release string
	started string
}

func (s *sumEnv) runs() int {
	b, _ := os.ReadFile(s.count)
	return strings.Count(string(b), "run")
}

// round syncs and waits for every summary it started.
func (s *sumEnv) round() Stats {
	st := s.e.Sync()
	s.e.sumWG.Wait()
	return st
}

func (s *sumEnv) note(t *testing.T) string {
	t.Helper()
	n := notes(t, s.vault)
	if len(n) != 1 {
		t.Fatalf("notes = %v", n)
	}
	b, _ := os.ReadFile(n[0])
	return string(b)
}

func conv(id, cwd string, n int) session.Session {
	s := mk(id, cwd)
	s.Messages = nil
	for i := 0; i < n; i++ {
		role := "user"
		if i%2 == 1 {
			role = "assistant"
		}
		s.Messages = append(s.Messages, session.Message{Role: role, Text: fmt.Sprintf("message %d of %s", i, id), Time: time.Now()})
	}
	return s
}

func setupSummaries(t *testing.T, mode string, sessions []session.Session, mut func(*config.Config)) *sumEnv {
	t.Helper()
	f := &fake{sessions: sessions}
	dir := t.TempDir()
	t.Setenv("CORTEX_FAKE_MODE", mode)
	s := &sumEnv{f: f, vault: filepath.Join(dir, "vault"), count: filepath.Join(dir, "count"), prompt: filepath.Join(dir, "prompt"),
		release: filepath.Join(dir, "release"), started: filepath.Join(dir, "started")}
	t.Setenv("CORTEX_FAKE_COUNT", s.count)
	t.Setenv("CORTEX_FAKE_PROMPT", s.prompt)
	t.Setenv("CORTEX_FAKE_RELEASE", s.release)
	t.Setenv("CORTEX_FAKE_STARTED", s.started)
	cfg := &config.Config{Vault: s.vault, Summaries: config.Summaries{
		Enabled: true, Tool: "custom", Projects: []string{"alpha"},
		Command: []string{os.Args[0], "-test.run=TestHelperSummariser"},
	}}
	if mut != nil {
		mut(cfg)
	}
	cfgPath := filepath.Join(dir, "cfg", "config.json")
	if err := cfg.Save(cfgPath); err != nil {
		t.Fatal(err)
	}
	e, err := New(cfgPath, []collector.Collector{f})
	if err != nil {
		t.Fatal(err)
	}
	s.e = e
	s.clk = &clock{t: time.Now()}
	e.now = s.clk.Now
	e.runner.Timeout = 20 * time.Second
	t.Cleanup(e.Stop)
	return s
}

func TestSummaryEndToEnd(t *testing.T) {
	s := setupSummaries(t, "ok", []session.Session{conv("a1", "/work/alpha", 4)}, nil)
	s.round()
	if s.runs() != 0 {
		t.Fatal("summarised a note that is still being written")
	}
	s.clk.Add(14 * time.Minute)
	s.round()
	if s.runs() != 0 {
		t.Fatal("summarised before idle_minutes (15 by default)")
	}
	s.clk.Add(2 * time.Minute)
	s.round()
	if s.runs() != 1 {
		t.Fatalf("runs = %d", s.runs())
	}
	note := s.note(t)
	if !strings.Contains(note, "## Summary") || !strings.Contains(note, "Fake summary.") || !strings.Contains(note, "Generated by a custom command") {
		t.Fatalf("no summary in\n%s", note)
	}
	if strings.Index(note, "cortex:summary:start") > strings.Index(note, "<!-- cortex:start -->") {
		t.Error("summary is not before the conversation")
	}
	p, _ := os.ReadFile(s.prompt)
	if !strings.Contains(string(p), "message 0 of a1") || strings.Contains(string(p), "token=abcdef") {
		t.Errorf("prompt = %q", p)
	}
	if st := s.e.Snapshot().Summaries; st.DoneThisHour != 1 || st.Queued != 0 || st.LastError != "" {
		t.Errorf("state = %+v", st)
	}

	// Same content: nothing runs, however many rounds pass.
	for i := 0; i < 3; i++ {
		s.clk.Add(time.Hour)
		s.round()
	}
	if s.runs() != 1 {
		t.Fatalf("an up-to-date summary was run again: %d", s.runs())
	}
	// A restart collects everything again: still one comparison, no run.
	s.e.Update(func(c *config.Config) {})
	s.round()
	if s.runs() != 1 {
		t.Fatalf("rerun after re-collecting: %d", s.runs())
	}

	// New content: summarised again once it has been quiet, and replaced, not duplicated.
	// The note is rewritten now, in real time: put the test clock there too.
	s.f.sessions[0] = conv("a1", "/work/alpha", 6)
	s.clk.Set(time.Now())
	if st := s.round(); st.Updated != 1 {
		t.Fatalf("stats = %+v", st)
	}
	s.round()
	if s.runs() != 1 {
		t.Fatal("summarised changed content before it was idle")
	}
	s.clk.Add(16 * time.Minute)
	s.round()
	if s.runs() != 2 || strings.Count(s.note(t), "cortex:summary:start") != 1 {
		t.Fatalf("runs = %d\n%s", s.runs(), s.note(t))
	}
}

func TestSummaryIdleUsesTheNotesModTime(t *testing.T) {
	s := setupSummaries(t, "ok", []session.Session{conv("a1", "/work/alpha", 4)}, func(c *config.Config) { c.Summaries.IdleMinutes = 5 })
	s.round()
	old := s.clk.Now().Add(-6 * time.Minute)
	os.Chtimes(notes(t, s.vault)[0], old, old)
	s.round()
	if s.runs() != 1 {
		t.Fatalf("runs = %d, want 1 with idle_minutes = 5 and a 6 minute old note", s.runs())
	}
	if m, _ := os.Stat(notes(t, s.vault)[0]); !m.ModTime().Equal(old.Truncate(time.Nanosecond)) && m.ModTime().Sub(old) > time.Second {
		t.Error("writing the summary moved the note's modification time")
	}
}

func TestSummaryGates(t *testing.T) {
	cases := []struct {
		name string
		sess session.Session
		mut  func(*config.Config)
		want int
	}{
		{"selected project", conv("a", "/work/alpha", 4), nil, 1},
		{"too short", conv("a", "/work/alpha", 3), nil, 0},
		{"project not selected", conv("a", "/work/beta", 6), nil, 0},
		{"chat without a project", conv("a", "/home/someone", 6), func(c *config.Config) { c.Summaries.Projects = []string{"someone", "home"} }, 0},
		{"switched off", conv("a", "/work/alpha", 6), func(c *config.Config) { c.Summaries.Enabled = false }, 0},
		{"paused", conv("a", "/work/alpha", 6), func(c *config.Config) { c.Paused = true }, 0},
		{"no tool", conv("a", "/work/alpha", 6), func(c *config.Config) { c.Summaries.Tool = "" }, 0},
		{"preset not installed", conv("a", "/work/alpha", 6), func(c *config.Config) { c.Summaries.Tool = "claude" }, 0},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			s := setupSummaries(t, "ok", []session.Session{c.sess}, c.mut)
			s.e.lookPath = func(string) (string, error) { return "", os.ErrNotExist }
			s.round()
			s.clk.Add(time.Hour)
			s.round()
			if s.runs() != c.want {
				t.Errorf("runs = %d, want %d", s.runs(), c.want)
			}
		})
	}
}

