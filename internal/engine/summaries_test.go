func TestSummaryRateLimit(t *testing.T) {
	s := setupSummaries(t, "ok", []session.Session{conv("a1", "/work/alpha", 4), conv("b1", "/work/alpha", 4), conv("c1", "/work/alpha", 4)},
		func(c *config.Config) { c.Summaries.MaxPerHour = 2 })
	s.round()
	s.clk.Add(20 * time.Minute)
	s.round()
	if s.runs() != 2 {
		t.Fatalf("runs = %d, want 2 (max_per_hour)", s.runs())
	}
	if q := s.e.Snapshot().Summaries.Queued; q != 1 {
		t.Errorf("queued = %d, want the third", q)
	}
	s.clk.Add(30 * time.Minute) // 30 minutes after the first start: still inside the hour
	s.round()
	if s.runs() != 2 {
		t.Fatalf("runs = %d inside the window", s.runs())
	}
	s.clk.Add(31 * time.Minute)
	s.round()
	if s.runs() != 3 {
		t.Fatalf("runs = %d after the window", s.runs())
	}
}

func TestSummaryFailureBackoffAndVisibleError(t *testing.T) {
	s := setupSummaries(t, "fail", []session.Session{conv("a1", "/work/alpha", 4)}, nil)
	s.round()
	s.clk.Add(20 * time.Minute)
	s.round()
	if s.runs() != 1 {
		t.Fatalf("runs = %d", s.runs())
	}
	st := s.e.Snapshot()
	if !strings.Contains(st.Summaries.LastError, "boom: not logged in") || strings.Contains(st.Summaries.LastError, "message 0") {
		t.Errorf("last error = %q", st.Summaries.LastError)
	}
	if len(st.Errors) != 1 || !strings.Contains(st.Errors[0], "boom") {
		t.Errorf("errors = %v", st.Errors)
	}
	// The round clears its own warnings; the failure stays listed.
	s.clk.Add(5 * time.Minute)
	s.round()
	if len(s.e.Snapshot().Errors) != 1 || s.runs() != 1 {
		t.Errorf("errors = %v, runs = %d", s.e.Snapshot().Errors, s.runs())
	}
	s.clk.Add(30 * time.Minute) // 35 minutes after the failure
	s.round()
	if s.runs() != 1 {
		t.Fatal("retried inside the hour")
	}
	s.clk.Add(30 * time.Minute) // past the hour
	s.round()
	if s.runs() != 2 {
		t.Fatalf("not retried after the hour: %d", s.runs())
	}
	if strings.Contains(s.note(t), "## Summary") {
		t.Error("a failed run left a summary")
	}
}

