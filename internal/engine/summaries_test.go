func waitFor(t *testing.T, path string) {
	t.Helper()
	for i := 0; i < 500; i++ {
		if _, err := os.Stat(path); err == nil {
			return
		}
		time.Sleep(20 * time.Millisecond)
	}
	t.Fatalf("%s never appeared", path)
}

// The tools' own sessions, started in the work folder, must not become notes.
func TestSessionsFromTheWorkFolderAreDropped(t *testing.T) {
	f := &fake{}
	e, cfgPath, root := setup(t, f)
	work := summarize.WorkDir(cfgPath)
	f.sessions = []session.Session{
		mk("own1", work), mk("own2", filepath.Join(work, "sub", "dir")), mk("own3", work+string(filepath.Separator)),
		mk("near", work+"-not"), mk("real", "/work/alpha"),
	}
	st := e.Sync()
	if st.Created != 2 || len(notes(t, root)) != 2 {
		t.Fatalf("stats = %+v, notes = %v", st, notes(t, root))
	}
	for _, p := range e.Snapshot().Projects {
		if strings.Contains(p.Name, "summaries-work") && p.Name != "summaries-work-not" {
			t.Errorf("work folder listed as a project: %+v", p)
		}
	}
	if n := e.Snapshot().Chats; n != 0 {
		t.Errorf("chats = %d", n)
	}
	if res, err := e.Ingest(&session.Session{Source: "x", ID: "pushed", Cwd: work, Messages: []session.Message{{Role: "user", Text: "hi"}}}, true); err != nil || res != IngestSkipped {
		t.Errorf("ingest = %q %v", res, err)
	}
}

func TestSummaryStateAndUpdateRules(t *testing.T) {
	s := setupSummaries(t, "ok", nil, nil)
	s.e.lookPath = func(name string) (string, error) {
		if name == "codex" {
			return "/bin/codex", nil
		}
		return "", os.ErrNotExist
	}
	st := s.e.Snapshot().Summaries
	if !st.Enabled || st.Tool != "custom" || !st.CustomAvailable || len(st.Command) != 2 || st.Command[0] != os.Args[0] ||
		len(st.Projects) != 1 || st.IdleMinutes != 15 || st.MaxPerHour != 20 {
		t.Errorf("state = %+v", st)
	}
	avail := map[string]bool{}
	for _, p := range st.Presets {
		avail[p.ID] = p.Available
	}
	if len(avail) != 2 || avail["claude"] || !avail["codex"] {
		t.Errorf("presets = %+v", st.Presets)
	}
	if err := s.e.Update(func(c *config.Config) { c.Summaries.Tool = "codex" }); err != nil {
		t.Fatal(err)
	}
	if got := s.e.Snapshot().Summaries.Command; got[0] != "codex" || got[len(got)-1] != "-" {
		t.Errorf("command = %v", got)
	}
	// The command that was written by hand survives a change made from the panel.
	disk, _ := config.LoadFile(s.e.path)
	if len(disk.Summaries.Command) != 2 {
		t.Errorf("saved command = %v", disk.Summaries.Command)
	}
	if err := s.e.Update(func(c *config.Config) { c.Summaries.Tool = "rm -rf" }); err == nil {
		t.Error("unknown tool accepted")
	}
	if err := s.e.Update(func(c *config.Config) { c.Summaries.Tool = "custom"; c.Summaries.Command = nil }); err == nil {
		t.Error("custom without a command accepted")
	}
	if s.e.Snapshot().Summaries.Tool != "codex" {
		t.Error("a refused update changed something")
	}
}

func TestSummarizeNote(t *testing.T) {
	// Not selected, not idle, rate limit zero-ish: none of it matters here.
	s := setupSummaries(t, "ok", []session.Session{conv("a1", "/work/beta", 2)}, func(c *config.Config) {
		c.Summaries.Enabled = false
		c.Summaries.MaxPerHour = 1
	})
	s.round()
	path := notes(t, s.vault)[0]
	for i := 0; i < 2; i++ {
		out, err := s.e.SummarizeNote(path)
		if err != nil || out != "Fake summary." {
			t.Fatalf("out=%q err=%v", out, err)
		}
	}
	rel, _ := filepath.Rel(s.vault, path)
	if _, err := s.e.SummarizeNote(rel); err != nil {
		t.Errorf("relative path: %v", err)
	}
	if !strings.Contains(s.note(t), "## Summary") || strings.Count(s.note(t), "cortex:summary:start") != 1 {
		t.Error("no single summary block")
	}
	if _, err := s.e.SummarizeNote("../nope.md"); err == nil {
		t.Error("a path outside the vault was accepted")
	}

	s.e.Update(func(c *config.Config) { c.Summaries.Tool = "" })
	if _, err := s.e.SummarizeNote(path); err == nil || !strings.Contains(err.Error(), "no usable summary tool") {
		t.Errorf("without a tool: %v", err)
	}
}
