// testdata/opencode-1.19.5.sql is a dump of what the real OpenCode 1.19.5
// (`opencode run`, custom OpenAI-compatible provider answering canned text
// from a local fake server) wrote to opencode.db: the real CREATE TABLE and
// CREATE INDEX statements of project, session, message, part and
// session_message, and every row of them. Only sandbox paths were replaced by
// /home/dev/demo. What this release does:
//   - storage is SQLite, tables session/message/part with the JSON in "data"
//     (the v1 layout); session_message exists but stays empty and there is no
//     session_v2, so the v2 layout must not be selected;
//   - `opencode run "two words"` stores the prompt as "\"two words\"" (quoted);
//   - the session title is generated by the (small) model: here the canned
//     answer; the placeholder "New session - <date>" is replaced by it;
//   - a bash tool call is a "tool" part (tool=bash, state.input.command) and
//     its output sits in state.output; a model step is one assistant message
//     with step-start/text/tool/step-finish parts.

func ms(n int64) time.Time { return time.UnixMilli(n) }

func realDB(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	script, err := os.ReadFile(filepath.Join("testdata", "opencode-1.19.5.sql"))
	if err != nil {
		t.Fatal(err)
	}
	db, err := sql.Open("sqlite", "file:"+filepath.Join(root, "opencode.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(string(script)); err != nil {
		t.Fatal(err)
	}
	return root
}

func TestRealOpenCode(t *testing.T) {
	title := "Canned answer number 2. Hello from the fake model."
	canned := func(n string) string { return "Canned answer number " + n + ". Hello from the fake model." }
	want := map[string]session.Session{
		"ses_e1afc9889ffebt8bqDqO6kddcc": {Source: ID, Cwd: "/home/dev/demo", Title: title, Messages: []session.Message{
			{Role: "user", Text: "Say hello single turn", Time: ms(1794843568016)},
			{Role: "assistant", Text: canned("1"), Time: ms(1794843568540)},
		}},
		// tool call + result, then `opencode run --continue` in the same session
		"ses_e1afc8187ffemRsb9igmZ1B574": {Source: ID, Cwd: "/home/dev/demo", Title: title, Messages: []session.Message{
			{Role: "user", Text: "Please RUNTOOL and tell me the output", Time: ms(1794843573905)},
			// one tool line, no tool output; two assistant messages (model steps) merged
			{Role: "assistant", Text: "I will run a command.\n\n> `bash` echo cortex-check\n\nTool done: output was cortex-check. FINAL-ANSWER", Time: ms(1794843574400)},
			{Role: "user", Text: "Second prompt of the same session", Time: ms(1794843575608)},
			{Role: "assistant", Text: canned("2"), Time: ms(1794843576115)},
		}},
		"ses_e1afc7488ffeLuMKbKanDq17wr": {Source: ID, Cwd: "/home/dev/demo/sub/dir", Title: title, Messages: []session.Message{
			{Role: "user", Text: "Hello from the subdirectory", Time: ms(1794843577234)},
			{Role: "assistant", Text: canned("1"), Time: ms(1794843577724)},
		}},
	}
	r := collect(newC(realDB(t)))
	if len(r.warns) != 0 {
		t.Fatal(r.warns)
	}
	if len(r.got) != 4 { // the fourth is `opencode run Unquoted words here`, checked below
		t.Fatalf("got %d sessions", len(r.got))
	}
	for _, s := range r.got {
		w, ok := want[s.ID]
		if !ok {
			if len(s.Messages) != 2 || s.Messages[0].Text != "Unquoted words here" {
				t.Errorf("unexpected session %+v", s)
			}
			continue
		}
		if s.Source != w.Source || s.Cwd != w.Cwd || s.Title != w.Title || len(s.Messages) != len(w.Messages) {
			t.Errorf("%s: %+v", s.ID, s)
			continue
		}
		for i, m := range w.Messages {
			if g := s.Messages[i]; g.Role != m.Role || g.Text != m.Text || !g.Time.Equal(m.Time) {
				t.Errorf("%s message %d:\n got %+v\nwant %+v", s.ID, i, g, m)
			}
		}
	}
}

func TestUnquoteRun(t *testing.T) {
	for in, want := range map[string]string{
		`"two words"`:            "two words",
		`"say \"hi\" now"`:       `say "hi" now`,
		`plain`:                  "plain",
		`"quoted" and "more"`:    `"quoted" and "more"`,
		`"a" b "c"`:              `"a" b "c"`,
		`"`:                      `"`,
		`it's "fine" here`:       `it's "fine" here`,
		`"unterminated \"inner"`: `unterminated "inner`,
	} {
		if got := unquoteRun(in); got != want {
			t.Errorf("unquoteRun(%q) = %q, want %q", in, got, want)
		}
	}
}
