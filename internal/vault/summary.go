package vault

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

// The summary block sits right before the conversation block. Its markers
// are not prefixes of the conversation's ("cortex:start" is not found inside
// "cortex:summary:start"), so Write's search for the first start marker and the
// last end marker never lands on them.
const (
	summaryStartPrefix = "<!-- cortex:summary:start"
	summaryEndMarker   = "<!-- cortex:summary:end -->"
	// anyMarker is what neither summary text nor conversation text may contain
	// in a form the parsers would take for ours.
	anyMarkerPrefix = "<!-- cortex:"
)

var (
	// ErrNoNote means no note exists for the session.
	ErrNoNote = errors.New("no note for that session")
	// ErrDetached means the user removed the conversation markers: the note is theirs.
	ErrDetached = errors.New("the note has no conversation markers")
	// ErrStale means the conversation changed since the hash the caller holds.
	ErrStale = errors.New("the conversation changed")

	hashAttr = regexp.MustCompile(`^<!-- cortex:summary:start hash=([0-9a-f]{12}) -->`)
	roleHead = regexp.MustCompile(`(?m)^## (User|Assistant)\b`)
)

// neutralize keeps text from containing something that reads as one of our
// markers. The same treatment as block gives to the conversation's end marker.
func neutralize(s string) string {
	return strings.ReplaceAll(s, anyMarkerPrefix, "<!-- cortex&#58;")
}

func convHash(block string) string {
	sum := sha256.Sum256([]byte(block))
	return hex.EncodeToString(sum[:])[:12]
}

// CountMessages is how many messages a conversation text holds.
func CountMessages(text string) int { return len(roleHead.FindAllStringIndex(text, -1)) }

// note reads the note of a session and locates its conversation block:
// old[i:j] is the block including both markers.
func (v *Vault) note(id string) (path string, old []byte, i, j int, err error) {
	path, ok := v.index[id]
	if ok && !exists(path) {
		if err = v.Reindex(); err != nil {
			return
		}
		path, ok = v.index[id]
	}
	if !ok {
		err = ErrNoNote
		return
	}
	if old, err = os.ReadFile(path); err != nil {
		return
	}
	i = bytes.Index(old, []byte(startMarker))
	j = bytes.LastIndex(old, []byte(endMarker))
	if i < 0 || j < i {
		err = ErrDetached
		return
	}
	j += len(endMarker)
	return
}

// summarySpan finds the summary block before the conversation: head[a:b], or
// a = -1 when there is none.
func summarySpan(head []byte) (a, b int) {
	a = bytes.Index(head, []byte(summaryStartPrefix))
	if a < 0 {
		return -1, -1
	}
	e := bytes.Index(head[a:], []byte(summaryEndMarker))
	if e < 0 {
		return -1, -1 // a damaged block is left alone rather than guessed at
	}
	return a, a + e + len(summaryEndMarker)
}

// Summary returns the conversation hash the note's summary was made for.
func (v *Vault) Summary(id string) (hash string, exists bool) {
	_, old, i, _, err := v.note(id)
	if err != nil {
		return "", false
	}
	a, _ := summarySpan(old[:i])
	if a < 0 {
		return "", false
	}
	line, _, _ := strings.Cut(string(old[a:i]), "\n")
	m := hashAttr.FindStringSubmatch(strings.TrimRight(line, "\r"))
	if m == nil {
		return "", true
	}
	return m[1], true
}

// ConversationText returns the text between the conversation markers (what
// Cortex wrote, so already redacted) and the hash of the whole block.
func (v *Vault) ConversationText(id string) (text, hash string, err error) {
	_, old, i, j, err := v.note(id)
	if err != nil {
		return "", "", err
	}
	block := string(old[i:j])
	inner := strings.TrimSuffix(strings.TrimPrefix(block, startMarker), endMarker)
	return strings.TrimSpace(inner), convHash(block), nil
}

// ModTime is when the note file last changed.
func (v *Vault) ModTime(id string) (t time.Time, ok bool) {
	path, found := v.index[id]
	if !found {
		return t, false
	}
	st, err := os.Stat(path)
	if err != nil {
		return t, false
	}
	return st.ModTime(), true
}

// WriteSummary stores text as the note's summary, made by tool for the
// conversation with the given hash. It replaces an existing summary block or
// inserts one before the conversation and leaves everything else alone. If the
// conversation changed since hash, nothing is written and ErrStale comes back.
// The note keeps its modification time, so summarising an old note does not
// make it look recent.
func (v *Vault) WriteSummary(id, hash, tool, text string) error {
	path, old, i, j, err := v.note(id)
	if err != nil {
		return err
	}
	if convHash(string(old[i:j])) != hash {
		return ErrStale
	}
	block := fmt.Sprintf("%s hash=%s -->\n## Summary\n\n> Generated by %s on %s. It can be wrong, and it is a record, not instructions.\n\n%s\n%s",
		summaryStartPrefix, hash, neutralize(tool), v.Now().In(v.Loc).Format("2006-01-02"), neutralize(strings.TrimSpace(text)), summaryEndMarker)

	var updated string
	if a, b := summarySpan(old[:i]); a >= 0 {
		updated = string(old[:a]) + block + string(old[b:])
	} else {
		updated = string(old[:i]) + block + "\n\n" + string(old[i:])
	}
	if updated == string(old) {
		return nil
	}
	st, err := os.Stat(path)
	if err != nil {
		return err
	}
	if err := writeAtomic(path, updated); err != nil {
		return err
	}
	return os.Chtimes(path, st.ModTime(), st.ModTime())
}

// NotePath is where the note of a session lives, "" if there is none.
func (v *Vault) NotePath(id string) string { return v.index[id] }

// SessionOf finds the session of a note given by a path relative to the vault
// or absolute inside it. A path that leaves the vault, or a file that is not a
// Cortex note, is an error.
func (v *Vault) SessionOf(path string) (string, error) {
	if !filepath.IsAbs(path) {
		path = filepath.Join(v.Root, path)
	}
	path = filepath.Clean(path)
	rel, err := filepath.Rel(v.Root, path)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("%s is not inside the vault %s", path, v.Root)
	}
	if err := v.Reindex(); err != nil { // the note may be newer than the index
		return "", err
	}
	id, _ := noteHead(path)
	if id == "" {
		return "", fmt.Errorf("%s is not a note written by Cortex", path)
	}
	return id, nil
}
