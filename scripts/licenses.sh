#!/bin/sh
# Writes THIRD_PARTY_LICENSES.md at the repo root: every module compiled into the
# binary for any of the six release targets, with its licence files verbatim,
# plus the Go standard library's licence. Deterministic: sorted, no timestamps,
# no local paths. Run from anywhere; CI runs it and fails if the committed file
# is out of date.
#
#   scripts/licenses.sh
#
# Needs go, and the module cache filled (go mod download).
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/THIRD_PARTY_LICENSES.md
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
export LC_ALL=C

cd "$root"
main=$(go list -m)
: >"$work/all"
for goos_arch in windows/amd64 windows/arm64 darwin/amd64 darwin/arm64 linux/amd64 linux/arm64; do
  CGO_ENABLED=0 GOOS=${goos_arch%/*} GOARCH=${goos_arch#*/} \
    go list -deps -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}' ./cmd/cortex >>"$work/all"
done
# One line per module (the same module shows up for every target); the program's own module is not third-party.
grep -v '^$' "$work/all" | grep -v "^$main " | sort -u >"$work/modules"

{
  cat <<'HEADER'
# Third-party licences

Cortex is released under the MIT licence (see `LICENSE`). The programs in the
release archives also contain the Go modules below, and the Go standard
library, each under its own licence, reproduced here verbatim. The list is the
set of modules compiled into the binary for any release target (Windows, macOS
and Linux, amd64 and arm64), generated by `scripts/licenses.sh`.
HEADER
  while read -r path version dir; do
    printf '\n## %s %s\n' "$path" "$version"
    found=0
    for f in $(ls -1 "$dir" | sort); do
      [ -f "$dir/$f" ] || continue
      lower=$(printf '%s' "$f" | tr 'A-Z' 'a-z')
      case $lower in
        licen[sc]e* | copying* | notice*)
          found=1
          printf '\n### %s\n\n~~~~~~~~\n' "$f"
          cat "$dir/$f"
          [ -z "$(tail -c1 "$dir/$f")" ] || echo
          printf '~~~~~~~~\n'
          ;;
      esac
    done
    if [ $found = 0 ]; then
      echo "scripts/licenses.sh: no licence file found for $path $version" >&2
      exit 1
    fi
  done <"$work/modules"
  printf '\n## Go standard library\n\n### LICENSE\n\n~~~~~~~~\n'
  cat "$(go env GOROOT)/LICENSE"
  printf '~~~~~~~~\n'
} >"$work/out.md"
mv "$work/out.md" "$out"
echo "wrote $out"
